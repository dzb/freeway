package com.jujin.freeway.db.dialect;

import com.jujin.freeway.db.Database;
import com.jujin.freeway.db.SqlException;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * H2's own SQL dialect, parameterized by its execution mode. H2 is not a
 * PostgreSQL or MySQL subtype: MODE changes the SQL surface H2 accepts, while
 * H2 keeps its own information schema, DDL transaction behaviour and types.
 */
public final class H2Dialect implements Dialect {

    private static final Set<String> RESERVED = Dialect.buildReserved(
        "dual", "rownum", "sysdate", "systimestamp", "array", "identity", "if",
        "cached", "memory", "generated", "always", "checkpoint", "shutdown",
        "analyze", "backup", "call", "compress", "script", "merge", "explain"
    );

    private final H2Mode mode;

    public H2Dialect() {
        this(H2Mode.NATIVE);
    }

    public H2Dialect(H2Mode mode) {
        this.mode = java.util.Objects.requireNonNull(mode, "mode");
    }

    /** Returns the dialect for an H2 JDBC URL, including its MODE parameter. */
    public static H2Dialect of(String url) {
        return new H2Dialect(H2Mode.fromUrl(url));
    }

    public H2Mode mode() {
        return mode;
    }

    @Override
    public String dialectId() {
        return "h2";
    }

    @Override
    public char quoteChar() {
        return mode.isMySqlFamily() ? '`' : '"';
    }

    @Override
    public String identifierQuoteChars() {
        // H2 accepts ANSI double quotes and MySQL-style backticks in every mode.
        return "\"`";
    }

    @Override
    public boolean hashLineComments() {
        return mode.isMySqlFamily();
    }

    @Override
    public boolean backslashEscapesStrings() {
        return mode.isMySqlFamily();
    }

    @Override
    public boolean dollarQuoting() {
        return true;
    }

    @Override
    public boolean escapeStringPrefix() {
        return true;
    }

    @Override
    public boolean dropTableCascade() {
        return true;
    }

    @Override
    public String truncateTable(String tableName) {
        return "TRUNCATE TABLE " + quoteName(tableName) + " RESTART IDENTITY";
    }

    @Override
    public String generatedClause() {
        return "GENERATED BY DEFAULT AS IDENTITY";
    }

    /**
     * H2 accepts standard OFFSET/FETCH in every mode, including the Oracle,
     * MSSQLServer, Derby and STRICT modes that reject LIMIT.
     */
    @Override
    public String offsetOnlyClause(long offset) {
        return "OFFSET " + offset + " ROWS";
    }

    @Override
    public String limitClause(long limit) {
        return "FETCH FIRST " + limit + " ROWS ONLY";
    }

    @Override
    public String limitOffsetClause(long limit, long offset) {
        return "OFFSET " + offset + " ROWS FETCH NEXT " + limit + " ROWS ONLY";
    }

    @Override
    public boolean supportsIndexIfNotExists() {
        return true;
    }

    @Override
    public boolean supportsTransactionalDdl() {
        // H2 auto-commits DDL in every mode; a DDL statement cannot be rolled
        // back with the surrounding transaction (verified on H2 2.4.240).
        return false;
    }

    @Override
    public boolean supportsReturning() {
        return false;
    }

    @Override
    public boolean supportsOnConflict() {
        // H2 PostgreSQL mode accepts ON CONFLICT only with literal VALUES;
        // Freeway executes parameterized statements, where H2 rejects it.
        // H2's own MERGE is the usable upsert path in every mode.
        return false;
    }

    @Override
    public String upsertClause(List<String> conflictColumns, List<String> updateColumns) {
        if (!mode.isMySqlFamily()) {
            throw new SqlException(
                "H2 mode " + mode + " does not support ON CONFLICT DO UPDATE; "
                    + "use Orm.save (H2 MERGE) or raw SQL");
        }
        List<String> updates = new ArrayList<>(updateColumns.size());
        for (String col : updateColumns) {
            String q = quoteName(col);
            updates.add(q + " = VALUES(" + q + ")");
        }
        return " ON DUPLICATE KEY UPDATE " + String.join(", ", updates);
    }

    @Override
    public boolean supportsMergeUpsert() {
        return true;
    }

    @Override
    public String mergeUpsertStatement(String table, List<String> columns,
            List<String> keyColumns, String placeholders) {
        if (columns.isEmpty() || keyColumns.isEmpty()) {
            throw new SqlException("H2 MERGE requires columns and key columns");
        }
        String cols = columns.stream().map(this::quoteName)
            .collect(Collectors.joining(", "));
        String keys = keyColumns.stream().map(this::quoteName)
            .collect(Collectors.joining(", "));
        return "MERGE INTO " + quoteName(table) + " (" + cols + ") KEY (" + keys
            + ") VALUES (" + placeholders + ")";
    }

    @Override
    public String defaultUUIDType() {
        return "UUID";
    }

    @Override
    public String defaultBinaryType() {
        return "BINARY VARYING";
    }

    @Override
    public Set<String> existingTables(Database db) {
        return querySet(db,
            "SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE UPPER(TABLE_SCHEMA) = UPPER(?) AND TABLE_TYPE = 'BASE TABLE'",
            effectiveSchema());
    }

    @Override
    public Set<String> existingColumns(Database db, String tableName) {
        return querySet(db,
            "SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE UPPER(TABLE_NAME) = ? AND UPPER(TABLE_SCHEMA) = UPPER(?)",
            tableName.toUpperCase(Locale.ROOT), effectiveSchema());
    }

    @Override
    public Set<String> existingIndexes(Database db, String tableName) {
        return querySet(db,
            "SELECT INDEX_NAME FROM INFORMATION_SCHEMA.INDEXES WHERE UPPER(TABLE_NAME) = ? AND UPPER(TABLE_SCHEMA) = UPPER(?)",
            tableName.toUpperCase(Locale.ROOT), effectiveSchema());
    }

    @Override
    public Set<String> reservedWords() {
        return RESERVED;
    }
}

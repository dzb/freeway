package com.jujin.freeway.db.internal;

import com.jujin.freeway.db.PooledConnection;
import com.jujin.freeway.db.util.SqlTextParser;

import com.jujin.freeway.db.BatchQuery;
import com.jujin.freeway.db.ExecuteResult;
import com.jujin.freeway.db.SqlException;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

final class BatchQueryImpl implements BatchQuery {

    private static final Logger LOG = LoggerFactory.getLogger(
        BatchQueryImpl.class
    );
    private final DatabaseImpl db;
    private final DatabaseImpl.TxBinding boundBinding;
    private final String sql;
    private final SqlTextParser.Result parsed;
    private final boolean mayHaveGeneratedKeys;
    private final int positionalParameterCount;
    private List<Object[]> positionalRows = List.of();
    private List<Map<String, Object>> namedRows = List.of();

    BatchQueryImpl(
        DatabaseImpl db,
        DatabaseImpl.TxBinding boundBinding,
        String sql
    ) {
        this.db = db;
        this.boundBinding = boundBinding;
        this.sql = sql;
        this.parsed = SqlTextParser.parseNamed(sql, db.dialect());
        this.mayHaveGeneratedKeys = SqlTextParser.hasTopLevelInsert(sql, db.dialect());
        this.positionalParameterCount =
            SqlTextParser.paramIndexes(parsed.sql(), db.dialect()).size();
        SqlTextParser.requireNoMixedPlaceholders(sql, db.dialect());
    }

    @Override
    public BatchQuery rows(Object[]... rows) {
        this.positionalRows = rows == null
            ? List.of()
            : List.of(rows);
        this.namedRows = List.of();
        return this;
    }

    @Override
    public BatchQuery named(List<Map<String, Object>> rows) {
        this.namedRows = rows == null ? List.of() : List.copyOf(rows);
        this.positionalRows = List.of();
        return this;
    }

    @Override
    public List<ExecuteResult> execute() {
        if (boundBinding != null) {
            db.checkBound(boundBinding);
            // Bound: the batch joins the caller's transaction. No commit, no
            // restore, no release — those belong to whoever opened it.
            return executeBatch(boundBinding.conn());
        }
        // No transaction binding on this thread — if a transaction is active
        // on another thread, borrowing here would silently run outside it.
        db.checkNoForeignTransaction();
        try (OwnedTransaction owned = OwnedTransaction.begin(db, null)) {
            boolean committed = false;
            try {
                List<ExecuteResult> results = executeBatch(owned.connection());
                try {
                    owned.commit();
                } catch (SQLException e) {
                    throw new SqlException("Batch commit failed: " + e.getMessage(), e);
                }
                committed = true;
                return results;
            } finally {
                if (!committed) {
                    owned.rollbackQuietly();
                }
            }
        }
    }

    /** The statements of one batch, over a connection whose transaction the caller owns. */
    private List<ExecuteResult> executeBatch(PooledConnection conn) {
        try {
            var raw = conn.connection();
            int autoGeneratedKeys = mayHaveGeneratedKeys
                ? Statement.RETURN_GENERATED_KEYS
                : Statement.NO_GENERATED_KEYS;
            try (
                PreparedStatement stmt = raw.prepareStatement(
                    parsed.sql(),
                    autoGeneratedKeys
                )
            ) {
                stmt.setQueryTimeout(db.queryTimeoutSeconds());
                if (!namedRows.isEmpty()) {
                    for (int i = 0; i < namedRows.size(); i++) {
                        // Structure (key presence) is identical across rows —
                        // validate it once, then bind values per row.
                        bindRow(stmt, namedRows.get(i), i == 0);
                        stmt.addBatch();
                    }
                } else {
                    for (var row : positionalRows) {
                        if (row.length != positionalParameterCount) {
                            throw new SqlException(
                                "Parameter count mismatch in batch SQL: " +
                                    sql +
                                    ". Expected " +
                                    positionalParameterCount +
                                    " value(s) per row but got " +
                                    row.length
                            );
                        }
                        stmt.clearParameters();
                        for (int i = 0; i < row.length; i++) {
                            stmt.setObject(i + 1, StatementValues.bindValue(row[i]));
                        }
                        stmt.addBatch();
                    }
                }
                int[] counts = stmt.executeBatch();
                List<Long> ids = collectGeneratedKeys(stmt);

                List<ExecuteResult> results = new ArrayList<>(counts.length);
                for (int i = 0; i < counts.length; i++) {
                    Long id = i < ids.size() ? ids.get(i) : null;
                    results.add(new ExecuteResult(counts[i], id));
                }
                return results;
            }
        } catch (SQLException e) {
            LOG.warn("Batch execution failed: {}", sql, e);
            throw new SqlException(
                "Batch execution failed: " + e.getMessage(),
                e
            );
        }
    }

    private List<Long> collectGeneratedKeys(PreparedStatement stmt)
        throws SQLException {
        if (!mayHaveGeneratedKeys) {
            return List.of();
        }
        List<Long> ids = new ArrayList<>();
        try (ResultSet rs = stmt.getGeneratedKeys()) {
            while (rs.next()) {
                Object key = rs.getObject(1);
                if (key instanceof Number n) {
                    ids.add(n.longValue());
                }
            }
        }
        return ids;
    }



    /**
     * Binds one named-parameter row. {@code validateKeys} runs the full
     * missing/unknown key validation — pass true for the first row only;
     * every row shares the same parameter structure, so re-validating each
     * row is O(rows × params) busywork.
     */
    private void bindRow(PreparedStatement stmt, Map<String, Object> row, boolean validateKeys)
        throws SQLException {
        if (validateKeys) {
            for (String name : parsed.names()) {
                if (!row.containsKey(name)) {
                    throw new SqlException(
                        "Missing value for named parameter '" +
                            name +
                            "' in batch SQL: " +
                            sql
                    );
                }
            }
            for (String paramName : row.keySet()) {
                if (!parsed.names().contains(paramName)) {
                    throw new SqlException(
                        "Unknown named parameter '" +
                            paramName +
                            "' in batch SQL: " +
                            sql
                    );
                }
            }
        }
        for (int i = 0; i < parsed.names().size(); i++) {
            stmt.setObject(i + 1, StatementValues.bindValue(row.get(parsed.names().get(i))));
        }
    }
}

package com.jujin.freeway.db.dialect;

import com.jujin.freeway.db.SqlException;
import java.util.List;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Direct syntax-surface tests for the four built-in dialects — the pieces
 * that need no live {@code Database} (identifier quoting, lexing flags, DDL
 * fragments, DML clauses). Introspection queries ({@code existingTables} &amp;
 * co.) are covered indirectly by the H2-backed schema/migration tests.
 */
class DialectSyntaxTest {

    private final PostgresDialect postgres = new PostgresDialect();
    private final MySqlDialect mysql = new MySqlDialect();
    private final SqliteDialect sqlite = new SqliteDialect();
    private final H2Dialect h2 = new H2Dialect();
    private final H2Dialect h2Postgres = new H2Dialect(H2Mode.POSTGRESQL);
    private final H2Dialect h2MySql = new H2Dialect(H2Mode.MYSQL);

    @Test
    void dialectIdsAreStableAndDistinct() {
        assertEquals("postgresql", postgres.dialectId());
        assertEquals("mysql", mysql.dialectId());
        assertEquals("sqlite", sqlite.dialectId());
        assertEquals("h2", h2.dialectId());
    }

    @Test
    void identifierQuotingContract() {
        // Reserved words are quoted; the dialect's own quote char is used.
        assertEquals("\"select\"", postgres.quoteName("select"));
        assertEquals("\"select\"", h2.quoteName("select"));
        assertEquals("`select`", mysql.quoteName("select"));
        assertEquals("\"select\"", sqlite.quoteName("select"));
        // Plain lowercase identifiers pass through untouched.
        assertEquals("plain_name", postgres.quoteName("plain_name"));
        // Uppercase forces quoting (case preservation).
        assertEquals("\"FirstName\"", postgres.quoteName("FirstName"));
        // Non-letter first character forces quoting.
        assertEquals("\"1abc\"", postgres.quoteName("1abc"));
        assertFalse(postgres.needsQuoting(null));
        assertFalse(postgres.needsQuoting("plain_name"));
        assertTrue(postgres.needsQuoting("user"));      // COMMON_RESERVED
        assertTrue(postgres.needsQuoting("ORDER"));     // case-insensitive match
        // Every dialect's reserved set includes the common words.
        for (Dialect d : new Dialect[] {postgres, mysql, sqlite, h2}) {
            assertTrue(d.reservedWords().containsAll(Dialect.COMMON_RESERVED), d.dialectId());
        }
    }

    @Test
    void dialectSpecificReservedWords() {
        assertTrue(postgres.needsQuoting("window"));
        assertTrue(mysql.needsQuoting("status"));
        assertTrue(sqlite.needsQuoting("abort"));
        assertTrue(h2.needsQuoting("dual"));
    }

    @Test
    void quotingAndLexingFlags() {
        // MySQL: backtick generation, backtick+double-quote accepted input,
        // # line comments and backslash string escapes.
        assertEquals('`', mysql.quoteChar());
        assertEquals("\"`", mysql.identifierQuoteChars());
        assertTrue(mysql.hashLineComments());
        assertTrue(mysql.backslashEscapesStrings());
        assertFalse(mysql.dollarQuoting());
        assertFalse(mysql.escapeStringPrefix());
        // PostgreSQL/H2: ANSI quotes; H2 additionally accepts backticks.
        assertEquals('"', postgres.quoteChar());
        assertEquals("\"", postgres.identifierQuoteChars());
        assertTrue(postgres.dollarQuoting());
        assertTrue(postgres.escapeStringPrefix());
        assertEquals("\"`", h2.identifierQuoteChars());
        // SQLite: ANSI quotes plus backticks on input.
        assertEquals("\"`", sqlite.identifierQuoteChars());
    }

    @Test
    void postgresDdlAndClauses() {
        // Reserved-word table/column names exercise the quoting path.
        assertEquals("TRUNCATE TABLE \"order\" RESTART IDENTITY",
            postgres.truncateTable("order"));
        assertTrue(postgres.dropTableCascade());
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", postgres.generatedClause());
        assertEquals("LIMIT 2147483647 OFFSET 5", postgres.offsetOnlyClause(5));
        assertEquals("UUID", postgres.defaultUUIDType());
        assertEquals(" ON CONFLICT (\"order\") DO UPDATE SET \"key\" = EXCLUDED.\"key\"",
            postgres.upsertClause(List.of("order"), List.of("key")));
        assertTrue(postgres.supportsOnConflict());
        assertTrue(postgres.supportsReturning());
        assertTrue(postgres.supportsIndexIfNotExists());
        assertTrue(postgres.supportsTransactionalDdl());
        assertFalse(postgres.generatedPrimaryKeyInline());
        assertEquals("FOR UPDATE", postgres.forUpdateClause());
    }

    @Test
    void h2OwnDdlAndClauses() {
        assertEquals("h2", h2.dialectId());
        assertEquals("TRUNCATE TABLE \"order\" RESTART IDENTITY", h2.truncateTable("order"));
        assertTrue(h2.dropTableCascade());
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", h2.generatedClause());
        assertEquals("OFFSET 5 ROWS", h2.offsetOnlyClause(5));
        assertEquals("FETCH FIRST 5 ROWS ONLY", h2.limitClause(5));
        assertEquals("OFFSET 2 ROWS FETCH NEXT 5 ROWS ONLY", h2.limitOffsetClause(5, 2));
        assertEquals("UUID", h2.defaultUUIDType());
        assertEquals("BINARY VARYING", h2.defaultBinaryType());
        assertFalse(h2.supportsOnConflict());
        assertFalse(h2.supportsReturning());
        assertTrue(h2.supportsIndexIfNotExists());
        assertFalse(h2.supportsTransactionalDdl());
        assertFalse(h2.generatedPrimaryKeyInline());
        assertEquals("FOR UPDATE", h2.forUpdateClause());
        assertTrue(h2.supportsMergeUpsert());
        assertEquals(
            "MERGE INTO \"order\" (id, \"key\") KEY (id) VALUES (?, ?)",
            h2.mergeUpsertStatement("order", List.of("id", "key"), List.of("id"), "?, ?"));
        assertThrows(SqlException.class,
            () -> h2.upsertClause(List.of("id"), List.of("key")));
        assertTrue(h2.needsQuoting("dual"));
        assertTrue(h2.needsQuoting("array"));
    }

    @Test
    void h2ModesChangeTheCompatibilitySurfaceOnly() {
        assertFalse(h2Postgres.supportsOnConflict());
        assertFalse(h2Postgres.supportsReturning());
        assertFalse(h2Postgres.supportsTransactionalDdl());
        assertThrows(SqlException.class,
            () -> h2Postgres.upsertClause(List.of("id"), List.of("key")));

        assertEquals(96, h2MySql.quoteChar());
        assertTrue(h2MySql.hashLineComments());
        assertTrue(h2MySql.backslashEscapesStrings());
        assertFalse(h2MySql.supportsOnConflict());
        assertEquals(" ON DUPLICATE KEY UPDATE `key` = VALUES(`key`)",
            h2MySql.upsertClause(List.of("order"), List.of("key")));
        assertFalse(h2MySql.supportsTransactionalDdl());
        assertEquals("h2", h2MySql.dialectId());
        assertEquals(H2Mode.POSTGRESQL,
            H2Dialect.of("jdbc:h2:mem:x;MODE=PostgreSQL").mode());
        assertEquals(H2Mode.MYSQL,
            H2Dialect.of("jdbc:h2:mem:x;mode=mysql").mode());
        assertEquals(H2Mode.NATIVE,
            H2Dialect.of("jdbc:h2:mem:x").mode());
        assertThrows(IllegalArgumentException.class,
            () -> H2Mode.fromUrl("jdbc:h2:mem:x;MODE=not-a-mode"));
    }

    @Test
    void mysqlSqliteSpecialCases() {
        // MySQL: no ON CONFLICT/RETURNING, VALUES() upsert syntax, no
        // transactional DDL (implicit commit per statement).
        assertEquals(" ON DUPLICATE KEY UPDATE `key` = VALUES(`key`)",
            mysql.upsertClause(List.of("order"), List.of("key")));
        assertFalse(mysql.supportsOnConflict());
        assertFalse(mysql.supportsReturning());
        assertFalse(mysql.supportsIndexIfNotExists());
        assertFalse(mysql.supportsTransactionalDdl());
        assertEquals("LIMIT 18446744073709551615 OFFSET 5", mysql.offsetOnlyClause(5));
        assertEquals("AUTO_INCREMENT", mysql.generatedClause());
        assertEquals("DATETIME(6)", mysql.defaultInstantType());
        assertEquals("LONGBLOB", mysql.defaultBinaryType());
        assertEquals("TRUNCATE TABLE `order`", mysql.truncateTable("order"));

        // SQLite: no TRUNCATE, no row locks; inline generated PK; ADD COLUMN
        // NOT NULL unsupported.
        assertEquals("DELETE FROM \"order\"", sqlite.truncateTable("order"));
        assertEquals("", sqlite.forUpdateClause());
        assertEquals("LIMIT -1 OFFSET 5", sqlite.offsetOnlyClause(5));
        assertEquals("AUTOINCREMENT", sqlite.generatedClause());
        assertTrue(sqlite.generatedPrimaryKeyInline());
        assertFalse(sqlite.alterAddColumnNotNull());
        assertEquals("TEXT", sqlite.defaultUUIDType());
        assertEquals("TEXT", sqlite.defaultInstantType());
        assertEquals("BLOB", sqlite.defaultBinaryType());
        assertEquals("INTEGER", sqlite.generatedTypeOverride("BIGINT", Long.class));
    }
}
